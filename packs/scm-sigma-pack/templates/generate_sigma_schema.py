#!/usr/bin/env python3
"""GENERATOR (deterministic) -- projects ontology.ttl into sigma.schema.json.

This script is the sole lawful path from the canonical RDF source
(../ontology.ttl) to the JSON Schema projection. The projection is a
consequence of the ontology, never a second source of truth: do not
hand-edit sigma.schema.json.

Usage:
    python3 generate_sigma_schema.py > sigma.schema.json

Determinism: classes are sorted by local name before serialization, no
timestamps or other nondeterministic fields are emitted, and json.dumps
uses fixed key order (sort_keys=True) -- running this twice must produce
byte-identical output.
"""
import json
import sys
from pathlib import Path

import rdflib

RDFS = rdflib.RDFS
SIGMA = rdflib.Namespace("https://chatman.dev/scm/sigma#")


def load_ontology(path):
    g = rdflib.Graph()
    g.parse(path, format="turtle")
    return g


def extract_elements(g):
    """Return {local_name: {zCoordinates: [...], jurisdictions: [...], comment: str}}."""
    elements = {}
    for cls in g.subjects(rdflib.RDF.type, SIGMA.Element):
        local = str(cls).rsplit("#", 1)[-1]
        z_coords = sorted(str(o) for o in g.objects(cls, SIGMA.zCoordinate))
        jurisdictions = sorted(str(o) for o in g.objects(cls, SIGMA.jurisdiction))
        comments = list(g.objects(cls, RDFS.comment))
        comment = str(comments[0]) if comments else ""
        elements[local] = {
            "zCoordinates": z_coords,
            "jurisdictions": jurisdictions,
            "comment": comment,
        }
    return elements


def build_schema(elements):
    properties = {}
    for name in sorted(elements.keys()):
        info = elements[name]
        properties[name] = {
            "type": "object",
            "description": info["comment"],
            "properties": {
                "zCoordinates": {
                    "type": "array",
                    "items": {"type": "string", "enum": ["P", "Gamma", "Omega", "B", "tau", "J", "A", "R"]},
                    "minItems": 1,
                },
                "jurisdictions": {
                    "type": "array",
                    "items": {"type": "string"},
                    "minItems": 1,
                },
            },
            "required": ["zCoordinates", "jurisdictions"],
        }
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": "https://chatman.dev/scm/sigma.schema.json",
        "title": "SCM Canonical Sigma Elements",
        "description": "GENERATED by templates/generate_sigma_schema.py from ../ontology.ttl. Do not hand-edit.",
        "type": "object",
        "properties": properties,
        "required": sorted(elements.keys()),
    }


def main():
    here = Path(__file__).resolve().parent
    ontology_path = here.parent / "ontology.ttl"
    g = load_ontology(str(ontology_path))
    elements = extract_elements(g)
    schema = build_schema(elements)
    json.dump(schema, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
